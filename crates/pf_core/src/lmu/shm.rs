//! Le Mans Ultimate shared memory: the `LMU_Data` mapping the game publishes
//! itself (Settings > Gameplay > Enable Plugins, then a restart).
//!
//! # Where these offsets come from
//!
//! S397 ships the C++ headers with the game (`Support\SharedMemoryInterface`)
//! but their licence forbids redistribution, so the header is **not vendored**
//! here. Every constant below was produced by compiling the shipped header
//! locally with MSVC and printing `sizeof`/`offsetof` (see
//! `docs/lmu-shared-memory.md`), then cross-checked against TinyPedal's
//! `pyLMUSharedMemory` (MIT), which transcribes the same header into ctypes.
//! `tests/lmu_shm_layout.rs` pins every number against a golden byte dump
//! generated by that same compiled header — if S397 moves a field, it fails.
//!
//! # Two packings in one mapping
//!
//! `InternalsPlugin.hpp` wraps its structs in `#pragma pack(push, 4)`, so
//! `TelemInfoV01` and friends are 4-byte packed. The `SharedMemory*` wrappers
//! in `SharedMemoryInterface.hpp` are declared *after* the matching `pop`, so
//! they use default alignment. Mixing the two up silently shifts every offset,
//! which is why the wrapper layout lives here as arithmetic constants with
//! their own asserts rather than as more packed structs.

use std::ffi::c_void;
use std::sync::atomic::{AtomicI32, Ordering};
use std::time::{Duration, Instant};

use crate::{Error, Result};

