// Sizes are the load-bearing part of the transcription: if a pad is wrong, the
// struct is the wrong size and this fails at compile time rather than silently
// decoding garbage in a race.
const _: () = assert!(std::mem::size_of::<TelemWheelV01>() == 260);
const _: () = assert!(std::mem::size_of::<TelemInfoV01>() == 1_888);
const _: () = assert!(std::mem::size_of::<VehicleScoringInfoV01>() == 584);
const _: () = assert!(std::mem::size_of::<ScoringInfoV01>() == 548);

/// Decode one transcribed struct out of a byte buffer at `offset`.
///
/// The reader itself copies straight from the mapping; this is how a byte dump
/// (the golden layout fixture, or a future capture) is read back through the
/// same transcription.
pub fn read_struct<T: Copy>(bytes: &[u8], offset: usize) -> Option<T> {
    let size = std::mem::size_of::<T>();
    let end = offset.checked_add(size)?;
    if end > bytes.len() {
        return None;
    }
    // SAFETY: bounds are checked above, `T: Copy` is one of the packed
    // transcripts (plain old data, no invalid bit patterns, alignment 4 or
    // less), and the read is unaligned so an arbitrary offset is fine.
    Some(unsafe { bytes.as_ptr().add(offset).cast::<T>().read_unaligned() })
}

/// Trim a fixed-width C string field to a `String`.
pub fn c_str(bytes: &[u8]) -> String {
    let end = bytes.iter().position(|&b| b == 0).unwrap_or(bytes.len());
    String::from_utf8_lossy(&bytes[..end]).into_owned()
}

// -------------------------------------------------------------- the reader

/// One decimated copy of the parts of the mapping we use.
pub struct Snapshot {
    pub telem: TelemInfoV01,
    pub scoring: ScoringInfoV01,
    /// Only the first `num_vehicles` entries are populated.
    pub vehicles: Vec<VehicleScoringInfoV01>,
    pub num_vehicles: usize,
    pub player_idx: usize,
    pub player_has_vehicle: bool,
}

impl Snapshot {
    /// Assemble a snapshot from already-decoded parts — how a replay or a
    /// layout test builds one without a running game.
    pub fn from_parts(
        telem: TelemInfoV01,
        scoring: ScoringInfoV01,
        vehicles: Vec<VehicleScoringInfoV01>,
    ) -> Self {
        let num_vehicles = vehicles.len().min(MAX_VEHICLES);
        let mut all = vehicles;
        all.resize(MAX_VEHICLES, unsafe { std::mem::zeroed() });
        Snapshot {
            telem,
            scoring,
            vehicles: all,
            num_vehicles,
            player_idx: 0,
            player_has_vehicle: num_vehicles > 0,
        }
    }

    /// A zeroed snapshot: the starting state of the Windows reader's
    /// preallocated buffers. Only `shm_win::Reader` assembles live snapshots,
    /// so this is gated with the reader — [`Snapshot::from_parts`] is the
    /// portable, tested construction path.
    #[cfg(windows)]
    fn new() -> Self {
        Snapshot {
            // SAFETY: both are plain old data with no padding invariants and no
            // Drop; all-zero is a valid (if meaningless) bit pattern, and every
            // field is overwritten before the snapshot is read.
            telem: unsafe { std::mem::zeroed() },
            scoring: unsafe { std::mem::zeroed() },
            vehicles: vec![unsafe { std::mem::zeroed() }; MAX_VEHICLES],
            num_vehicles: 0,
            player_idx: 0,
            player_has_vehicle: false,
        }
    }

    /// The player's scoring row, matched by the telemetry slot id rather than
    /// by index: the two arrays are written by different subsystems and are not
    /// guaranteed to be in the same order.
    pub fn player_scoring(&self) -> Option<&VehicleScoringInfoV01> {
        let id = self.telem.m_id;
        self.vehicles[..self.num_vehicles]
            .iter()
            .find(|v| v.m_id == id)
            .or_else(|| {
                self.vehicles[..self.num_vehicles]
                    .iter()
                    .find(|v| v.m_is_player != 0)
            })
    }

    pub fn vehicles(&self) -> &[VehicleScoringInfoV01] {
        &self.vehicles[..self.num_vehicles]
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn c_str_stops_at_the_nul_not_the_end_of_the_field() {
        let mut field = [0u8; 32];
        field[..4].copy_from_slice(b"LMP3");
        field[10] = b'X'; // garbage past the terminator, as real fields carry
        assert_eq!(c_str(&field), "LMP3");
    }

    #[test]
    fn a_field_with_no_terminator_still_decodes() {
        assert_eq!(c_str(&[b'a'; 4]), "aaaa");
    }
}
