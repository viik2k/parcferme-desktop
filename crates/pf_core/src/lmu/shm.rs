// ------------------------------------------------------------ wrapper layout

/// `sizeof(SharedMemoryLayout)`. Four bytes larger than the sum of its parts:
/// the trailing padding that default alignment adds for the 8-byte `size_t`
/// inside `SharedMemoryScoringData`.
pub const LAYOUT_SIZE: usize = 324_824;
/// `offsetof(SharedMemoryObjectOut, scoring)` — i.e. `sizeof(generic) + sizeof(paths)`.
pub const OFF_SCORING: usize = 1_632;
/// `offsetof(SharedMemoryObjectOut, telemetry)`.
pub const OFF_TELEMETRY: usize = 128_464;
const SCORING_SIZE: usize = 126_832;
/// `offsetof(SharedMemoryScoringData, vehScoringInfo)` — 548 bytes of
/// `ScoringInfoV01`, 4 of alignment padding, then the 8-byte `scoringStreamSize`.
pub const OFF_VEH_ARRAY: usize = 560;
/// `offsetof(SharedMemoryTelemetryData, telemInfo)`; the three leading `u8`s
/// are followed by one byte of padding.
pub const OFF_TELEM_ARRAY: usize = 4;
const OFF_ACTIVE_VEHICLES: usize = 0;
const OFF_PLAYER_IDX: usize = 1;
/// The fixed array bound in both payloads. A larger `mNumVehicles` than this
/// would mean a header change; we clamp rather than read past the array.
pub const MAX_VEHICLES: usize = 104;

// The wrappers are arithmetic rather than structs (nothing in them needs
// naming), so their "size asserts" are the relations between the constants.
const _: () = assert!(OFF_TELEMETRY == OFF_SCORING + SCORING_SIZE);
const _: () = assert!(SCORING_SIZE == OFF_VEH_ARRAY + MAX_VEHICLES * VEH_SIZE + 65_536);
const _: () =
    assert!(LAYOUT_SIZE == OFF_TELEMETRY + OFF_TELEM_ARRAY + MAX_VEHICLES * TELEM_SIZE + 4);

const TELEM_SIZE: usize = std::mem::size_of::<TelemInfoV01>();
const VEH_SIZE: usize = std::mem::size_of::<VehicleScoringInfoV01>();
const SCORING_INFO_SIZE: usize = std::mem::size_of::<ScoringInfoV01>();

