//! Le Mans Ultimate shared memory: the `LMU_Data` mapping the game publishes
//! itself (Settings > Gameplay > Enable Plugins, then a restart).
//!
//! # Where these offsets come from
//!
//! S397 ships the C++ headers with the game (`Support\SharedMemoryInterface`)
//! but their licence forbids redistribution, so the header is **not vendored**
//! here. Every constant below was produced by compiling the shipped header
//! locally with MSVC and printing `sizeof`/`offsetof` (see
//! `docs/lmu-shared-memory.md`), then cross-checked against TinyPedal's
//! `pyLMUSharedMemory` (MIT), which transcribes the same header into ctypes.
//! `tests/lmu_shm_layout.rs` pins every number against a golden byte dump
//! generated by that same compiled header — if S397 moves a field, it fails.
//!
//! # Two packings in one mapping
//!
//! `InternalsPlugin.hpp` wraps its structs in `#pragma pack(push, 4)`, so
//! `TelemInfoV01` and friends are 4-byte packed. The `SharedMemory*` wrappers
//! in `SharedMemoryInterface.hpp` are declared *after* the matching `pop`, so
//! they use default alignment. Mixing the two up silently shifts every offset,
//! which is why the wrapper layout lives here as arithmetic constants with
//! their own asserts rather than as more packed structs.
//!
//! # The portable half and the Windows half (issue #35)
//!
//! Everything in this file is plain data work — sizes, offsets, decode
//! helpers, a snapshot — with no OS in it, so it builds and tests on any
//! host, and `tests/lmu_shm_layout.rs` pins the numbers against the golden
//! dump from Linux CI as well as Windows. The reader itself cannot be
//! portable: it opens win32 **named kernel objects** (the `LMU_Data`
//! section, the data event, the lock section and its event), and Proton
//! does not bridge those into the Linux namespace — so even with the game
//! running under Proton on Linux there is nothing for a native process to
//! open. That half lives in [`shm_win`](self::win), compiled only on
//! Windows and re-exported from here so the existing
//! `lmu::shm::{Reader, Wake}` path keeps working. On non-Windows those two
//! items simply don't exist, and `Lmu::start` answers
//! [`crate::Error::LmuNotRunning`] (see `lmu.rs`).

// The Windows half: kernel32 FFI, the process scan, the game's lock and the
// `Reader`. `#[path]` because a bare `mod shm_win;` here would resolve under
// `lmu/shm/`; the attribute keeps the file beside this one, where the issue
// #35 split put it. Gated out entirely on other hosts — a cfg-stripped module
// is never even resolved, so no Linux build ever sees a kernel32 import.
#[cfg(windows)]
#[path = "shm_win.rs"]
mod win;

// Re-exported so existing callers keep using `lmu::shm::Reader` /
// `lmu::shm::Wake` exactly as before the split: the module path is public API,
// the inner module is an implementation detail.
#[cfg(windows)]
pub use win::{Reader, Wake};

/// The process name the game runs under. Matched case-insensitively by the
/// Windows reader's process scan (see `shm_win.rs`); a transcription fact, so
/// it lives with the rest of the layout rather than in the reader.
pub const GAME_EXE: &str = "Le Mans Ultimate.exe";

// ------------------------------------------------------------ wrapper layout

/// `sizeof(SharedMemoryLayout)`. Four bytes larger than the sum of its parts:
/// the trailing padding that default alignment adds for the 8-byte `size_t`
/// inside `SharedMemoryScoringData`.
pub const LAYOUT_SIZE: usize = 324_824;
/// `offsetof(SharedMemoryObjectOut, scoring)` — i.e. `sizeof(generic) + sizeof(paths)`.
pub const OFF_SCORING: usize = 1_632;
/// `offsetof(SharedMemoryObjectOut, telemetry)`.
pub const OFF_TELEMETRY: usize = 128_464;
const SCORING_SIZE: usize = 126_832;
/// `offsetof(SharedMemoryScoringData, vehScoringInfo)` — 548 bytes of
/// `ScoringInfoV01`, 4 of alignment padding, then the 8-byte `scoringStreamSize`.
pub const OFF_VEH_ARRAY: usize = 560;
/// `offsetof(SharedMemoryTelemetryData, telemInfo)`; the three leading `u8`s
/// are followed by one byte of padding.
pub const OFF_TELEM_ARRAY: usize = 4;
// The two flag offsets below (and `SCORING_INFO_SIZE` further down) are
// consumed only by the Windows reader's memcpy in `shm_win.rs`, so they are
// gated with it — on a non-Windows build nothing reaches them, and dead
// private constants would fail the `-D warnings` lint. The values themselves
// are transcription facts like every other constant in this section.
#[cfg(windows)]
const OFF_ACTIVE_VEHICLES: usize = 0;
#[cfg(windows)]
const OFF_PLAYER_IDX: usize = 1;
/// The fixed array bound in both payloads. A larger `mNumVehicles` than this
/// would mean a header change; we clamp rather than read past the array.
pub const MAX_VEHICLES: usize = 104;

// The wrappers are arithmetic rather than structs (nothing in them needs
// naming), so their "size asserts" are the relations between the constants.
const _: () = assert!(OFF_TELEMETRY == OFF_SCORING + SCORING_SIZE);
const _: () = assert!(SCORING_SIZE == OFF_VEH_ARRAY + MAX_VEHICLES * VEH_SIZE + 65_536);
const _: () =
    assert!(LAYOUT_SIZE == OFF_TELEMETRY + OFF_TELEM_ARRAY + MAX_VEHICLES * TELEM_SIZE + 4);

const TELEM_SIZE: usize = std::mem::size_of::<TelemInfoV01>();
const VEH_SIZE: usize = std::mem::size_of::<VehicleScoringInfoV01>();
// Gated with the reader, same reason as the two offsets above.
#[cfg(windows)]
const SCORING_INFO_SIZE: usize = std::mem::size_of::<ScoringInfoV01>();

// --------------------------------------------------------- packed transcript

/// `TelemWheelV01`. Corner order across all four-element arrays is **FL, FR,
/// RL, RR**, per the header's own comment on `mWheel[4]`.
#[repr(C, packed(4))]
#[derive(Clone, Copy)]
pub struct TelemWheelV01 {
    _pad0: [u8; 24],
    /// **Kelvin**, despite the header commenting it as Celsius. Measured
    /// 2026-09-07 against a live session: a cold car in the garage reads
    /// 293.18 (ambient 20 °C, not 293 °C) and rises to ~873 under braking.
    /// The comment is wrong; the data is not.
    pub m_brake_temp: f64,
    _pad32: [u8; 88],
    /// kPa.
    pub m_pressure: f64,
    /// Kelvin, sampled left / centre / right across the tread. Reads a flat
    /// 0.0 — not ambient — until the car has been on track, so zero means
    /// "not populated yet", never "absolute zero".
    pub m_temperature: [f64; 3],
    /// Tyre **life remaining**, 1.0 fresh falling toward 0 — *not* wear, in
    /// spite of the field name and the header's "wear (0.0-1.0, fraction of
    /// maximum)". Measured over a five-lap stint: 1.0 → 0.933. Same direction
    /// as the REST `wearables.tires`, so reading it as wear inverts every
    /// alert.
    pub m_wear: f64,
    _pad160: [u8; 44],
    /// Kelvin.
    pub m_tire_carcass_temperature: f64,
    _pad212: [u8; 48],
}

